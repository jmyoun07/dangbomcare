-- ==========================================================
-- [260728] user_consents 마케팅 동의(선택) 3개 컬럼 신설
-- ==========================================================
-- 배경:
--   260728 우노헬스케어가 기존 문서(260723 최종안)에 '마케팅 활용 및 광고성 정보 수신 동의'를
--   5번 항목으로 순수 추가했다. 기존 4개 항목은 변경 없음.
--     ① 이용약관  ② 개인정보 수집·이용  ③ 민감정보 수집·이용  ④ 제3자 제공   ← 필수 4개 (기존)
--     ⑤ 마케팅 활용 및 광고성 정보 수신                                      ← 이 마이그레이션 (선택)
--
--   ⑤는 **선택** 항목이다. 동의하지 않아도 회원가입·기본 서비스에 제한이 없다.
--   → 앱의 필수 동의 게이트(hasConsents)에 marketing 을 절대 포함시키지 않는다.
--     (백엔드에는 게이트 판정 코드가 없다. 판정은 앱 NavGraph/Splash 가 개별 bool 로 수행)
--
-- 시각 컬럼(accepted_at / revoked_at)이 따로 필요한 이유:
--   우노 문서가 마케팅 동의의 '수집·이용 항목'에 "마케팅 수신 동의 여부, 동의·철회 시각,
--   광고성 정보 발송 및 수신 이력"을 명시했다.
--   기존 user_consents.accepted_at 은 필수 동의를 받은 시각 하나뿐이라
--   이후 반복되는 마케팅 동의/철회 이력을 담을 수 없다(설정 화면 토글로 언제든 켜고 끔).
--   → 마지막 동의 시각 / 마지막 철회 시각을 별도 컬럼으로 보관한다.
--   (전체 이력 테이블이 아니라 '마지막 시각'이다. 발송 이력은 이 테이블 범위 밖)
--
-- 기본값 FALSE 인 이유:
--   기존 가입자는 마케팅 동의를 실제로 받은 적이 없으므로 FALSE 가 사실에 부합.
--   선택 항목이라 재동의를 강제하지 않는다(동의 화면으로 다시 보내지 않음).
--   임의로 TRUE 로 채우면 받지 않은 동의를 받은 것처럼 기록하게 되므로 금지.
--   같은 이유로 두 시각 컬럼은 NULL 로 시작한다(동의·철회한 적 없음 = NULL).
-- ==========================================================

ALTER TABLE public.user_consents
  ADD COLUMN IF NOT EXISTS marketing_accepted BOOLEAN NOT NULL DEFAULT FALSE;

-- 마지막으로 마케팅 동의를 받은 시각 (동의한 적 없으면 NULL)
ALTER TABLE public.user_consents
  ADD COLUMN IF NOT EXISTS marketing_accepted_at TIMESTAMPTZ NULL;

-- 마지막으로 마케팅 동의를 철회한 시각 (철회한 적 없으면 NULL)
ALTER TABLE public.user_consents
  ADD COLUMN IF NOT EXISTS marketing_revoked_at TIMESTAMPTZ NULL;
