-- ==========================================================
-- [260726] user_consents.third_party_accepted 신설
-- ==========================================================
-- 배경:
--   260723 최종안에서 회원가입 필수 동의가 4개로 확정됨.
--     ① 이용약관  ② 개인정보 수집·이용  ③ 민감정보 수집·이용
--     ④ 개인정보 및 민감정보 제3자 제공  ← 이 컬럼
--   기존에는 앱 화면에서 체크만 받고 서버에 저장하지 않아
--   (ConsentsScreen "[임시] thirdParty는 화면·로컬 필수만") 동의 이력이 남지 않았음.
--
-- 기본값 FALSE 인 이유:
--   기존 가입자는 4번째 동의를 실제로 받은 적이 없으므로 FALSE 가 사실에 부합.
--   앱은 hasConsents 게이트에서 third_party 가 false 인 사용자를 동의 화면으로
--   다시 보내 4번째 동의를 받는다. (임의로 TRUE 로 채우면 받지 않은 동의를
--   받은 것처럼 기록하게 되므로 금지)
-- ==========================================================

ALTER TABLE public.user_consents
  ADD COLUMN IF NOT EXISTS third_party_accepted BOOLEAN NOT NULL DEFAULT FALSE;
