   "전날은 🍷 음주가 있으셨네요. 술을 드신 밤에는 간이 알코올을 분해하느라 밤사이 혈당을 올려주는 일을 제대로 못 해서 다음날 아침 공복혈당이 낮게 나오는 경우가 많은데, 오늘 아침은 134 mg/dL로 평소 범위(130~150) 안에서 유지됐어요. 🍜 식사 후 추가로 드신 음식이 없었던 점이 크게 흔들리지 않는 데 함께 도움이 됐을 수 있어요. 오늘은 금주하시고, 저녁은 오후 7시 30분 전에 마치신 뒤 식사 후 30분 내 15분 걷기를 이어가 보세요."
