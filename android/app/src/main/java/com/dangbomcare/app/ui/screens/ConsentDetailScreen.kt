/**
 * 약관 전체 내용 화면. type = "terms" | "privacy" | "sensitive" | "thirdparty" | "marketing"
 * (연구 활용 동의는 v1.9에서 제거됨 — 사용자 피드백)
 * [260728] "marketing" 추가 — 선택 동의. NavGraph 의 "consent_detail/{type}" 라우트가
 *   type 문자열을 그대로 받으므로 라우트 변경 없이 진입한다.
 */
@Composable
fun ConsentDetailScreen(
    type: String,
    onBack: () -> Unit
) {
    val (title, body) = when (type) {
        "terms" -> "이용약관 (필수)" to TERMS_TEXT
        "privacy" -> "개인정보 수집·이용 동의 (필수)" to PRIVACY_TEXT
        "sensitive" -> "민감정보 수집·이용 동의 (필수)" to SENSITIVE_TEXT
        "thirdparty" -> "개인정보 및 민감정보 제3자 제공 동의 (필수)" to THIRD_PARTY_TEXT
        "marketing" -> "마케팅 활용 및 광고성 정보 수신 동의 (선택)" to MARKETING_TEXT
        else -> "약관" to "약관 내용이 없습니다."
    }

    Scaffold(
        containerColor = BgPrimary,
        topBar = {
            TopAppBar(
                title = { Text(title, fontWeight = FontWeight.Bold, fontSize = 16.sp) },
                navigationIcon = {
                    IconButton(onClick = onBack) {
                        Icon(Icons.AutoMirrored.Filled.ArrowBack, contentDescription = "뒤로")
                    }
                },
                colors = TopAppBarDefaults.topAppBarColors(containerColor = Primary, titleContentColor = androidx.compose.ui.graphics.Color.White, navigationIconContentColor = androidx.compose.ui.graphics.Color.White)
            )
        }
    ) { padding ->
        Column(
            modifier = Modifier
                .padding(padding)
                .fillMaxSize()
                .verticalScroll(rememberScrollState())
                .padding(horizontal = 20.dp, vertical = 16.dp)
        ) {
            // 약관 본문 (마크다운 스타일로 줄바꿈 처리)
            body.split("\n").forEach { line ->
                when {
                    line.startsWith("# ") -> {
                        Spacer(Modifier.height(4.dp))
                        Text(
                            line.removePrefix("# "),
                            fontSize = 22.sp,
                            fontWeight = FontWeight.Black,
                            color = Primary
                        )
                        Spacer(Modifier.height(12.dp))
                    }
                    line.startsWith("## ") -> {
                        Spacer(Modifier.height(16.dp))
                        Text(
                            line.removePrefix("## "),
                            fontSize = 17.sp,
                            fontWeight = FontWeight.Bold,
                            color = PrimaryDark
                        )
                        Spacer(Modifier.height(8.dp))
                    }
                    line.startsWith("- ") -> {
                        Row(modifier = Modifier.padding(vertical = 2.dp)) {
                            Text("• ", fontSize = 14.sp, color = TextPrimary)
                            Text(line.removePrefix("- "), fontSize = 14.sp, color = TextPrimary, lineHeight = 22.sp)
                        }
                    }
                    line.isBlank() -> Spacer(Modifier.height(10.dp))
                    else -> Text(line, fontSize = 14.sp, color = TextPrimary, lineHeight = 22.sp)
                }
            }
            Spacer(Modifier.height(40.dp))
        }
    }
}

